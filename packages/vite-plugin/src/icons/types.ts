import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

export interface IconTypesOptions {
  /**
   * `icon` only accepts the known names, URLs and raw SVG: a typo is an error
   * @default false
   */
  strict?: boolean
}

/**
 * The types of the icon names: `MazIconNames` of `maz-ui` augmented with every name. `maz-ui` and not
 * `@maz-ui/icons`: an augmentation of a module the project does not resolve is ignored without an error. The
 * import adds `maz-ui` to the program: an augmentation alone does not, its names would be lost in a project
 * that only imports the components (`maz-ui/components/MazIcon`).
 */
export function generateIconTypes(names: Iterable<string>, { strict = false }: IconTypesOptions = {}): string {
  const entries = [
    ...new Set(names),
  ]
    .sort()
    .map(name => `    '${name}': true`)

  return [
    '// Generated by MazUi() of @maz-ui/vite-plugin, do not edit',
    'import type {} from \'maz-ui\'',
    '',
    'declare module \'maz-ui\' {',
    '  interface MazIconNames {',
    ...entries,
    '  }',
    ...(strict
      ? [
          '',
          '  interface MazIconOptions {',
          '    strict: true',
          '  }',
        ]
      : []),
    '}',
    '',
  ].join('\n')
}

/** Writes the file only when its content changes, not to restart the type checker for nothing */
export function writeIfChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === content)
    return false

  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
  return true
}
