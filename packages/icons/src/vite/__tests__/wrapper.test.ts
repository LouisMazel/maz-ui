import type { Rollup } from 'vite'
import type { MazUiIconsOptions } from '../plugin.ts'
import { readFileSync, rmSync } from 'node:fs'
import { join } from 'node:path'
import { fileURLToPath } from 'node:url'
import ts from 'typescript'
import { build } from 'vite'
import { runCli } from '../cli.ts'
import { MazUiIcons } from '../plugin.ts'
import { createProject, HOME_SVG } from './fixtures.ts'

const PLUGIN = fileURLToPath(new URL('../index.ts', import.meta.url))
const ACME = 'node_modules/@acme/icons'
const CLI_OPTIONS = { command: 'acme-icons', plugin: 'acme:icons', pluginFunction: 'AcmeIcons()' }

const ACME_OPTIONS = `{
  name: 'acme:icons',
  typesModule: '@acme/icons',
  defaultIcons: false,
  dts: 'src/acme-icons.d.ts',
  dir: [{ path: '${ACME}/svg', svgo: false, import: name => ({ from: '@acme/icons/raw/' + name, name: 'Acme' }) }],
}`

const roots: string[] = []

function acmeProject(files: Record<string, string> = {}): string {
  const root = createProject({
    icons: 'none',
    files: {
      'node_modules/@maz-ui/icons/package.json': '{"name":"@maz-ui/icons","types":"index.d.ts"}',
      'node_modules/@maz-ui/icons/index.d.ts': 'export interface IconNames {}\nexport interface IconOptions {}\nexport type IconName = keyof IconNames\n',
      [`${ACME}/package.json`]: '{"name":"@acme/icons","type":"module","types":"index.d.ts","exports":{".":{"types":"./index.d.ts"},"./raw/*":"./raw/*.js"}}',
      [`${ACME}/index.d.ts`]: 'export type { IconName, IconNames, IconOptions } from \'@maz-ui/icons\'\n',
      [`${ACME}/svg/home.svg`]: HOME_SVG,
      [`${ACME}/raw/home.js`]: `export const Acme = ${JSON.stringify(HOME_SVG)}\n`,
      'vite.config.mjs': `import { MazUiIcons } from '${PLUGIN}'\n\nexport default { plugins: [MazUiIcons(${ACME_OPTIONS})] }\n`,
      ...files,
    },
  })
  roots.push(root)
  return root
}

afterAll(() => {
  for (const root of roots)
    rmSync(root, { recursive: true, force: true })
})

function createLogger() {
  return {
    log: vi.fn<(message: string) => void>(),
    error: vi.fn<(message: string) => void>(),
  }
}

function typeErrors(root: string, files: string[]): string[] {
  const program = ts.createProgram(files.map(file => join(root, file)), {
    strict: true,
    noEmit: true,
    module: ts.ModuleKind.ESNext,
    moduleResolution: ts.ModuleResolutionKind.Bundler,
    types: [],
    lib: ['lib.es5.d.ts'],
  })
  return ts.getPreEmitDiagnostics(program).map(diagnostic => ts.flattenDiagnosticMessageText(diagnostic.messageText, '\n'))
}

const acmeOptions: MazUiIconsOptions = {
  name: 'acme:icons',
  typesModule: '@acme/icons',
  defaultIcons: false,
  dts: false,
  dir: [{ path: `${ACME}/svg`, svgo: false, import: name => ({ from: `@acme/icons/raw/${name}`, name: 'Acme' }) }],
}

async function buildCode(root: string, isLib: boolean, options: MazUiIconsOptions = acmeOptions): Promise<string> {
  const entry = join(root, 'src/index.js')
  const output = await build({
    root,
    configFile: false,
    logLevel: 'silent',
    plugins: [MazUiIcons(options)],
    build: {
      write: false,
      minify: false,
      ...(isLib
        ? { lib: { entry, formats: ['es'] }, rollupOptions: { external: [/^@acme\/icons/] } }
        : { rollupOptions: { input: entry } }),
    },
  }) as Rollup.RollupOutput | Rollup.RollupOutput[]

  const { output: files } = Array.isArray(output)
    ? output[0]!
    : output
  return files.map(file => file.type === 'chunk'
    ? file.code
    : '').join('\n')
}

describe('given a library that wraps MazUiIcons() with its own name, module and command', () => {
  describe('when its command writes the types', () => {
    it('then they augment the module of the library, with its name', async () => {
      const root = acmeProject()
      const logger = createLogger()

      expect(await runCli(['types', '--root', root], logger, CLI_OPTIONS)).toBe(0)
      expect(logger.log).toHaveBeenCalledWith('[acme:icons] Types written in src/acme-icons.d.ts')
      expect(readFileSync(join(root, 'src/acme-icons.d.ts'), 'utf8')).toBe([
        '// Generated by acme:icons, do not edit',
        'import type {} from \'@acme/icons\'',
        '',
        'declare module \'@acme/icons\' {',
        '  interface IconNames {',
        '    \'home\': true',
        '  }',
        '}',
        '',
      ].join('\n'))
    })
  })

  describe('when an app types a name with the types of @maz-ui/icons and of the library', () => {
    it('then both have the names of the library', async () => {
      const root = acmeProject({
        'src/use.ts': [
          'import type { IconName } from \'@maz-ui/icons\'',
          'import type { IconName as AcmeIconName } from \'@acme/icons\'',
          '',
          'export const name: IconName = \'home\'',
          'export const acmeName: AcmeIconName = \'home\'',
          '// @ts-expect-error',
          'export const typo: AcmeIconName = \'hom\'',
          '',
        ].join('\n'),
      })
      await runCli(['types', '--root', root], createLogger(), CLI_OPTIONS)

      expect(typeErrors(root, ['src/acme-icons.d.ts', 'src/use.ts'])).toEqual([])
    })
  })

  describe('when its command runs without its plugin in the Vite config', () => {
    it('then it fails, with the function of the library', async () => {
      const root = acmeProject({ 'vite.config.mjs': 'export default {}\n' })
      const logger = createLogger()

      expect(await runCli(['types', '--root', root], logger, CLI_OPTIONS)).toBe(1)
      expect(logger.error).toHaveBeenCalledWith('[acme:icons] AcmeIcons() is not in the Vite config: add it')
    })
  })

  describe('when its command runs with a config that does not write the types', () => {
    it('then it fails, with the function of the library', async () => {
      const root = acmeProject({ 'vite.config.mjs': `import { MazUiIcons } from '${PLUGIN}'\n\nexport default { plugins: [MazUiIcons({ name: 'acme:icons', defaultIcons: false, dts: false })] }\n` })
      const logger = createLogger()

      expect(await runCli(['types', '--root', root], logger, CLI_OPTIONS)).toBe(1)
      expect(logger.error).toHaveBeenCalledWith('[acme:icons] AcmeIcons() does not write the types: remove `dts: false`')
    })
  })

  describe('when its command shows the help', () => {
    it('then the help has the command of the library', async () => {
      const logger = createLogger()

      expect(await runCli(['--help'], logger, CLI_OPTIONS)).toBe(0)
      expect(logger.log).toHaveBeenCalledWith(expect.stringMatching(/^acme-icons: the icons by name\n\nUsage:\n {2}acme-icons types/))
    })
  })

  describe('when an app that also imports the module of an icon is built', () => {
    it('then the SVG is bundled once, from the module', async () => {
      const root = acmeProject({
        'src/index.js': 'import { Acme } from "@acme/icons/raw/home"\n\nexport const a = { icon: "home", raw: Acme }\n',
      })
      const code = await buildCode(root, false)

      expect(code.match(/M3 12 12 3l9 9/g)).toHaveLength(1)
    })
  })

  describe('when a library that uses the names is built', () => {
    it('then its dist imports the module of the icon instead of copying the SVG', async () => {
      const root = acmeProject({
        'src/index.js': 'export const a = { icon: "home" }\n',
      })
      const code = await buildCode(root, true)

      expect(code).toMatch(/import \{ Acme as \w+ \} from "@acme\/icons\/raw\/home"/)
      expect(code).not.toContain('M3 12 12 3l9 9')
    })
  })

  describe('when a library is built with folders whose modules have a default export', () => {
    it('then its dist imports the default export of the module', async () => {
      const root = acmeProject({
        'src/index.js': 'export const a = { icon: "home", b: { icon: "acme:home" } }\n',
      })
      const code = await buildCode(root, true, {
        ...acmeOptions,
        dir: [
          { path: `${ACME}/svg`, import: name => `@acme/icons/svg/${name}` },
          { path: `${ACME}/svg`, prefix: 'acme', import: name => ({ from: `@acme/icons/named/${name}`, name: 'default' }) },
        ],
      })

      expect(code).toMatch(/import \w+ from "@acme\/icons\/svg\/home"/)
      expect(code).toMatch(/import [\w$]+ from "@acme\/icons\/named\/home"/)
    })
  })
})
