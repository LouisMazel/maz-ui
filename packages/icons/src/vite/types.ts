import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

/**
 * A module whose names the types augment: `@maz-ui/icons`, `maz-ui`, or a library that re-exports the types of
 * `@maz-ui/icons` (`@acme/icons`, with `export type { IconNames, IconOptions } from '@maz-ui/icons'`)
 */
export type IconTypesModule = '@maz-ui/icons' | 'maz-ui' | (string & Record<never, never>)

export interface IconTypesOptions {
  /**
   * `icon` only accepts the known names, URLs and raw SVG: a typo is an error
   * @default false
   */
  strict?: boolean
  /**
   * The module to augment, one the project resolves (`resolveIconTypesModule()`): `MazIconNames` of `maz-ui`, else
   * `IconNames` of the module (`@maz-ui/icons`, or a library that re-exports it: its names are the ones of `@maz-ui/icons`)
   * @default 'maz-ui'
   */
  module?: IconTypesModule
  /**
   * What writes the file, in its first line
   * @default 'MazUi() of @maz-ui/vite-plugin'
   */
  generator?: string
}

const MAZ_UI_INTERFACES = { names: 'MazIconNames', options: 'MazIconOptions' }
const ICONS_INTERFACES = { names: 'IconNames', options: 'IconOptions' }

/**
 * The types of the icon names: the names of the module augmented with every name. A module the project resolves: an
 * augmentation of a module it does not resolve is ignored without an error, but its import fails (with pnpm strict, an
 * app that only depends on `maz-ui` does not resolve `@maz-ui/icons`). The import adds the module to the program: an
 * augmentation alone does not, its names would be lost in a project that only imports the components
 * (`maz-ui/components/MazIcon`).
 */
export function generateIconTypes(names: Iterable<string>, { strict = false, module = 'maz-ui', generator = 'MazUi() of @maz-ui/vite-plugin' }: IconTypesOptions = {}): string {
  const interfaces = module === 'maz-ui'
    ? MAZ_UI_INTERFACES
    : ICONS_INTERFACES
  const entries = [
    ...new Set(names),
  ]
    .sort()
    .map(name => `    '${name}': true`)
  return [
    `// Generated by ${generator}, do not edit`,
    `import type {} from '${module}'`,
    '',
    `declare module '${module}' {`,
    `  interface ${interfaces.names} {`,
    ...entries,
    '  }',
    ...(strict
      ? [
          '',
          `  interface ${interfaces.options} {`,
          '    strict: true',
          '  }',
        ]
      : []),
    '}',
    '',
  ].join('\n')
}

/** Writes the file only when its content changes, not to restart the type checker for nothing */
export function writeIfChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === content)
    return false

  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
  return true
}
