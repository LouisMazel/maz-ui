import { existsSync, mkdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname } from 'node:path'

/** A module whose names the types augment */
export type IconTypesModule = '@maz-ui/icons' | 'maz-ui'

export interface IconTypesOptions {
  /**
   * `icon` only accepts the known names, URLs and raw SVG: a typo is an error
   * @default false
   */
  strict?: boolean
  /**
   * The module to augment, one the project resolves (`resolveIconTypesModule()`): `IconNames` of `@maz-ui/icons` (the
   * names of `maz-ui` include them), or `MazIconNames` of `maz-ui`
   * @default 'maz-ui'
   */
  module?: IconTypesModule
}

const INTERFACES: Record<IconTypesModule, { names: string, options: string }> = {
  '@maz-ui/icons': { names: 'IconNames', options: 'IconOptions' },
  'maz-ui': { names: 'MazIconNames', options: 'MazIconOptions' },
}

/**
 * The types of the icon names: the names of the module augmented with every name. A module the project resolves: an
 * augmentation of a module it does not resolve is ignored without an error, but its import fails (with pnpm strict, an
 * app that only depends on `maz-ui` does not resolve `@maz-ui/icons`). The import adds the module to the program: an
 * augmentation alone does not, its names would be lost in a project that only imports the components
 * (`maz-ui/components/MazIcon`).
 */
export function generateIconTypes(names: Iterable<string>, { strict = false, module = 'maz-ui' }: IconTypesOptions = {}): string {
  const entries = [
    ...new Set(names),
  ]
    .sort()
    .map(name => `    '${name}': true`)
  return [
    '// Generated by MazUi() of @maz-ui/vite-plugin, do not edit',
    `import type {} from '${module}'`,
    '',
    `declare module '${module}' {`,
    `  interface ${INTERFACES[module].names} {`,
    ...entries,
    '  }',
    ...(strict
      ? [
          '',
          `  interface ${INTERFACES[module].options} {`,
          '    strict: true',
          '  }',
        ]
      : []),
    '}',
    '',
  ].join('\n')
}

/** Writes the file only when its content changes, not to restart the type checker for nothing */
export function writeIfChanged(file: string, content: string): boolean {
  if (existsSync(file) && readFileSync(file, 'utf8') === content)
    return false

  mkdirSync(dirname(file), { recursive: true })
  writeFileSync(file, content)
  return true
}
