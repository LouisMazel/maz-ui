/**
 * Country codes that have a flag in `@maz-ui/icons` (uppercase, e.g. `FR`, `GE-AB`)
 */
export const countryFlagCodes = Object.keys(flagLoaders)

/**
 * Load the square flag of a country code from `@maz-ui/icons`, without network request to a third party.
 * Lookup: the whole code (`GE-AB`), then the same order as the CDN flags of `MazSelectCountry` (`fr`, then the region of `en-US`).
 * Made for the `flag-src` prop of `MazSelectCountry` and `MazInputPhoneNumber`.
 * @param code - country code, case insensitive (e.g. `FR`, `fr`, `en-US`)
 * @returns the flag as a `data:image/svg+xml` URL, or `undefined` when no flag exists for this code
 */
export async function loadCountryFlag(code: string): Promise<string | undefined> {
  const flagCode = [code, code.slice(0, 2), code.slice(3, 5)]
    .map(candidate => candidate.toUpperCase())
    .find(candidate => Object.hasOwn(flagLoaders, candidate))

  if (!flagCode) {
    return undefined
  }

  const flagModule = await flagLoaders[flagCode]()
  const svg = flagModule[`MazFlagSquare${flagCode.replace('-', '')}`]

  return typeof svg === 'string' ? `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}` : undefined
}
